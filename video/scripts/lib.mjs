// Shared helpers for the scripts (Node 22.18+/24 runs the .ts import natively).
import { bundle } from "@remotion/bundler";
import { copyFileSync, existsSync, linkSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildTimeline, defaultPacing } from "../src/kit/timeline.ts";

export const VIDEO_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
export const REPO_DIR = join(VIDEO_DIR, "..");
export const FPS = 30;

/** Per-video pacing overrides live next to the scenes: src/articles/<slug>/pacing.json. */
export function loadPacing(slug) {
  const file = join(VIDEO_DIR, "src", "articles", slug, "pacing.json");
  return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {};
}

export function loadNarration(slug) {
  return JSON.parse(readFileSync(join(VIDEO_DIR, "narration", `${slug}.json`), "utf8"));
}

export function loadTimeline(slug, lang) {
  const narration = loadNarration(slug);
  const timings = JSON.parse(readFileSync(join(VIDEO_DIR, "public", "audio", slug, lang, "timings.json"), "utf8"));
  const pacing = { ...defaultPacing, ...loadPacing(slug) };
  return { narration, timeline: buildTimeline(narration, timings, lang, FPS, pacing) };
}

/** Every video with a narration script. */
export function listSlugs() {
  return readdirSync(join(VIDEO_DIR, "narration"))
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.replace(/\.json$/, ""));
}

/** Composition ids are `<slug>-<lang>`. */
export function splitId(id) {
  const match = /^(.+)-(ja|en)$/.exec(id ?? "");
  if (!match) throw new Error(`Expected a composition id like <slug>-ja or <slug>-en, got "${id}"`);
  return { slug: match[1], lang: match[2] };
}

const entrySource = (slug) => `// Generated by scripts/lib.mjs: registers only the "${slug}" video.
import { registerRoot } from "remotion";
import * as article from "../src/articles/${slug}";
import type { VideoDefinition } from "../src/kit/ArticleVideo";
import { createRoot } from "../src/kit/root";

const definition = Object.values(article).find(
  (value): value is VideoDefinition => typeof value === "object" && value !== null && "slug" in value && "scenes" in value,
);
if (!definition) throw new Error("src/articles/${slug}/index.tsx must export a VideoDefinition");
registerRoot(createRoot([definition]));
`;

/**
 * Bundle a single video: a generated entry point that registers only src/articles/<slug>, and a
 * public dir holding only that video's narration audio (hard links). Bundles stay small and are
 * isolated from unfinished work on other videos. Always call cleanup() to delete the bundle.
 */
export async function bundleVideo(slug) {
  const audioDir = join(VIDEO_DIR, "public", "audio", slug);
  if (!existsSync(audioDir)) throw new Error(`No narration audio for "${slug}". Run \`npm run tts -- ${slug}\` first.`);

  const entryDir = join(VIDEO_DIR, ".entries");
  mkdirSync(entryDir, { recursive: true });
  const entryPoint = join(entryDir, `${slug}.tsx`);
  writeFileSync(entryPoint, entrySource(slug));

  const publicDir = join(VIDEO_DIR, ".public", slug);
  rmSync(publicDir, { recursive: true, force: true });
  for (const lang of readdirSync(audioDir)) {
    const from = join(audioDir, lang);
    const to = join(publicDir, "audio", slug, lang);
    mkdirSync(to, { recursive: true });
    for (const file of readdirSync(from).filter((f) => /^[^.]+\.wav$|^timings\.json$/.test(f))) {
      try {
        linkSync(join(from, file), join(to, file));
      } catch {
        copyFileSync(join(from, file), join(to, file));
      }
    }
  }

  const outDir = mkdtempSync(join(tmpdir(), `article-video-${slug}-`));
  const serveUrl = await bundle({ entryPoint, publicDir, outDir, rootDir: VIDEO_DIR });
  return { serveUrl, cleanup: () => rmSync(outDir, { recursive: true, force: true }) };
}
