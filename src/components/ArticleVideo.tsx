import videos from "@/data/article-videos.json";
import messagesJa from "../../messages/ja.json";
import messagesEn from "../../messages/en.json";

type VideoEntry = {
  src: string;
  poster: string;
  duration: number;
  transcript: string[];
};

const manifest = videos as Record<string, Partial<Record<"ja" | "en", VideoEntry>>>;

export function formatDuration(seconds: number): string {
  // Floor like the browser's media controls do, so the caption matches the player.
  const total = Math.floor(seconds);
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, "0")}`;
}

/**
 * Narrated explainer video for a blog post, rendered by the Remotion project in /video.
 * Assets live in public/videos/<slug>/ and metadata in src/data/article-videos.json
 * (both generated by `node video/scripts/render.mjs`).
 */
export function ArticleVideo({ slug, locale }: { slug: string; locale: string }) {
  const lang = locale === "en" ? "en" : "ja";
  const entry = manifest[slug]?.[lang];
  if (!entry) return null;
  const t = (lang === "en" ? messagesEn : messagesJa).articleVideo;

  return (
    <figure className="not-prose my-10">
      <div className="overflow-hidden rounded-2xl border border-border bg-surface-card shadow-[0_10px_30px_rgba(20,20,19,0.06)]">
        <video
          className="block aspect-video h-auto w-full bg-[#faf9f5]"
          controls
          playsInline
          preload="none"
          poster={entry.poster}
          aria-label={t.label}
        >
          <source src={entry.src} type="video/mp4" />
          <p className="p-4 text-sm">
            {t.unsupported} <a href={entry.src}>{t.download}</a>
          </p>
        </video>
      </div>
      <figcaption className="mt-3 flex flex-wrap items-baseline gap-x-2 gap-y-1 text-sm text-muted-foreground">
        <span className="font-medium text-foreground">{t.label}</span>
        <span aria-hidden="true">·</span>
        <span className="font-mono">{formatDuration(entry.duration)}</span>
        <span aria-hidden="true">·</span>
        <span>{t.narration}</span>
      </figcaption>
      <details className="mt-3 rounded-xl border border-border bg-muted/40 px-4 py-3 text-sm">
        <summary className="cursor-pointer select-none font-medium text-muted-foreground transition-colors hover:text-accent">
          {t.transcript}
        </summary>
        <div className="mt-3 space-y-3 leading-relaxed text-muted-foreground">
          {entry.transcript.map((paragraph, i) => (
            <p key={i}>{paragraph}</p>
          ))}
        </div>
      </details>
    </figure>
  );
}
