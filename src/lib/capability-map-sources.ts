import { t, type Link, type LinkKind } from "./capability-map-types";

const ref = (kind: LinkKind, title: string, ja: string, en: string, href: string): Link => ({
  kind,
  ja: title,
  en: title,
  meta: t(ja, en),
  href,
});

/** A paper or research report; `by` is [ja, en], e.g. ["Kaplan ら", "Kaplan et al."]. */
const paper = (title: string, by: [string, string], year: number, href: string): Link =>
  ref("paper", title, `${by[0]}（${year} 年）`, `${by[1]} (${year})`, href);

const post = (slug: string, ja: string, en: string): Link => ({ kind: "post", ja, en, slug });

